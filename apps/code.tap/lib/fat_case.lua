return function(path)
    if not path:find("[\128-\255]") then return path:upper() end
    local upper = {}
    local index = 1
    while index <= #path do
        local char, next_index = Encoding.decode(path, index)
        local converted = exceptions[char]
        if not converted then
            for _, range in ipairs(ranges) do
                local first, last, stride, offset = table.unpack(range)
                if char < first then break end
                if char <= last and (char - first) % stride == 0 then
                    converted = char + offset
                    break
                end
            end
        end
        upper[#upper + 1] = Encoding.encode(converted or char)
        index = next_index
    end
    return table.concat(upper)
end
